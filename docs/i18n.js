const records = [];
document.querySelectorAll("body *").forEach((element) => {
  if (element.closest(".start-title")) return;
  element.childNodes.forEach((node) => {
    if (node.nodeType !== Node.TEXT_NODE) return;
    const value = node.nodeValue.trim();
    if (!value || !translations[value]) return;
    records.push({ node, zh: value, en: translations[value] });
  });
});

const startTitle = {
  first: [...document.querySelectorAll(".start-title > .start-title-line:first-child i")],
  second: [...document.querySelectorAll(".start-title-cn i")]
};
const toggle = document.querySelector("#languageToggle");
const description = document.querySelector('meta[name="description"]');

function readSavedLanguage() {
  try {
    return localStorage.getItem("norain-language");
  } catch {
    return null;
  }
}

function saveLanguage(language) {
  try {
    localStorage.setItem("norain-language", language);
  } catch {
    // Language switching still works when file:// storage is unavailable.
  }
}

