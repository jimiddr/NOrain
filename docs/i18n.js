function applyLanguage(language) {
  const lang = language === "zh" ? "zh" : "en";
  records.forEach(({ node, zh, en }) => {
    const source = lang === "zh" ? zh : en;
    const leading = node.nodeValue.match(/^\s*/)?.[0] || "";
    const trailing = node.nodeValue.match(/\s*$/)?.[0] || "";
    node.nodeValue = `${leading}${source}${trailing}`;
  });

  const first = lang === "zh" ? ["让", "NOrain"] : ["Let", "NOrain"];
  const second = lang === "zh" ? ["开", "始", "下", "雨"] : ["Make", "It", "Rain", ""];
  startTitle.first.forEach((node, index) => { node.textContent = first[index] || ""; });
  startTitle.second.forEach((node, index) => {
    node.textContent = second[index] || "";
    node.hidden = !second[index];
  });

  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  document.title = meta[lang].title;
  description?.setAttribute("content", meta[lang].description);
  attributes.forEach(({ selector, name, zh, en }) => {
    document.querySelector(selector)?.setAttribute(name, lang === "zh" ? zh : en);
  });
  toggle.textContent = lang === "zh" ? "EN" : "中文";
  toggle.setAttribute("aria-label", lang === "zh" ? "Switch to English" : "切换到中文");
  saveLanguage(lang);
}

const requested = new URLSearchParams(location.search).get("lang");
const initial = requested === "zh" || requested === "en"
  ? requested
  : readSavedLanguage() || "en";
applyLanguage(initial);

toggle.addEventListener("click", () => {
  applyLanguage(document.documentElement.lang.startsWith("zh") ? "en" : "zh");
});

window.norainLanguage = () => document.documentElement.lang.startsWith("zh") ? "zh" : "en";
